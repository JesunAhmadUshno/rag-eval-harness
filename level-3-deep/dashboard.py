"""Level 3, Deep: the quality dashboard.

A plain markdown summary generated by run_deep.py from one actual run:
pass rates before and after reranking, metric means, failure taxonomy
counts, and judge cost accounting. No hand typed numbers: every value
comes from the summary dict the runner measured.
"""


def build_dashboard(summary):
    lines = []
    lines.append("# Quality dashboard: rag-eval-harness Deep run")
    lines.append("")
    lines.append(f"Golden set: {summary['n']} cases (level-3-deep/golden_set_deep.json)")
    lines.append("")
    lines.append("## Pass rates")
    lines.append("")
    lines.append(f"- Without rerank: {summary['without']['passed']} of {summary['without']['n']} "
                 f"passed, pass rate {summary['without']['pass_rate']:.3f}")
    lines.append(f"- With rerank: {summary['with']['passed']} of {summary['with']['n']} "
                 f"passed, pass rate {summary['with']['pass_rate']:.3f}")
    b11 = summary["b11"]
    lines.append(f"- b11 class ({b11['n']} cases): without rerank {b11['passed_without']} passed, "
                 f"with rerank {b11['passed_with']} passed")
    lines.append("")
    lines.append("## Metric means (with rerank)")
    lines.append("")
    lines.append(f"- Faithfulness: {summary['with']['mean_faithfulness']:.3f}")
    lines.append(f"- Context recall: {summary['with']['mean_context_recall']:.3f}")
    lines.append(f"- Answer relevance: {summary['with']['mean_answer_relevance']:.3f}")
    lines.append("")
    lines.append("## Failure taxonomy")
    lines.append("")
    tax = summary["taxonomy"]
    lines.append(f"- RAG failures without rerank: {tax['rag_failed']} of {summary['without']['n']} cases")
    lines.append(f"- RAG failures with rerank: {summary['rag_failed_with']} of {summary['with']['n']} cases")
    for label in sorted(tax["rag_counts"]):
        lines.append(f"  - {label}: {tax['rag_counts'][label]}")
    lines.append(f"- Agent failures: {tax['agent_failed']} of {summary['agent_tasks']} demo tasks")
    for label in sorted(tax["agent_counts"]):
        lines.append(f"  - {label}: {tax['agent_counts'][label]}")
    lines.append(f"- Total failures: {tax['total_failed']}, total labelled: {tax['total_labelled']}")
    lines.append("")
    lines.append("## Judge cost")
    lines.append("")
    judge = summary["judge"]
    lines.append(f"- BudgetedJudge: {judge['calls_made']} calls made, "
                 f"{judge['calls_skipped']} skipped, total cost {judge['total_cost']} units, "
                 f"judged pass {judge['judged_passed']} of {judge['judged']}")
    lines.append("")
    lines.append("Generated by level-3-deep/run_deep.py. Do not edit by hand.")
    lines.append("")
    return "\n".join(lines)


def write_dashboard(summary, path):
    text = build_dashboard(summary)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return text
